/* Original implementation of the inspected Qualcomm USB4 DROM wire format. */
#include <linux/crc32.h>
#include <linux/errno.h>
#include <linux/string.h>
#include <linux/unaligned.h>

#include "qcom-usb4-drom.h"

/* Revision/length, legacy IDs, adapter entries and product description. */
static const u8 qcom_usb4_drom_data[QCOM_USB4_DROM_SIZE - 13] = {
	0x01, 0x67, 0x00, 0x28, 0x03, 0x00, 0x00, 0x00, 0x00, 0x05, 0x86, 0x00,
	0x00, 0x00, 0x05, 0x87, 0x00, 0x00, 0x00, 0x1e, 0x01, 0x51, 0x75, 0x61,
	0x6c, 0x63, 0x6f, 0x6d, 0x6d, 0x20, 0x54, 0x65, 0x63, 0x68, 0x6e, 0x6f,
	0x6c, 0x6f, 0x67, 0x69, 0x65, 0x73, 0x2c, 0x20, 0x49, 0x6e, 0x63, 0x2e,
	0x00, 0x11, 0x02, 0x53, 0x6e, 0x61, 0x70, 0x64, 0x72, 0x61, 0x67, 0x6f,
	0x6e, 0x20, 0x30, 0x31, 0x42, 0x00, 0x0f, 0x09, 0x10, 0x04, 0xc6, 0x05,
	0x38, 0x09, 0x00, 0x00, 0xeb, 0x34, 0x00, 0x00, 0x00, 0x08, 0x82, 0x80,
	0x03, 0x00, 0x00, 0x00, 0x00, 0x08, 0x83, 0x90, 0x02, 0x00, 0x00, 0x00,
	0x00, 0x03, 0x84, 0x00, 0x03, 0x08, 0x06,
};

static u8 qcom_usb4_uid_crc(const u8 *data)
{
	u8 crc = 0xff;
	unsigned int i, bit;

	for (i = 0; i < 8; i++) {
		crc ^= data[i];
		for (bit = 0; bit < 8; bit++)
			crc = (crc << 1) ^ ((crc & 0x80) ? 0x07 : 0);
	}
	return crc;
}

int qcom_usb4_drom_build(u8 *data, size_t size, u32 serial, u8 router)
{
	u64 uid;
	u32 crc;

	if (!data || size < QCOM_USB4_DROM_SIZE || router > 2)
		return -EINVAL;

	uid = (0x5c6ULL << 48) | ((u64)serial << 4) | router;
	put_unaligned_le64(uid, data + 1);
	data[0] = qcom_usb4_uid_crc(data + 1);
	memcpy(data + 13, qcom_usb4_drom_data, sizeof(qcom_usb4_drom_data));
	crc = ~crc32c(~0U, data + 13, sizeof(qcom_usb4_drom_data));
	put_unaligned_le32(crc, data + 9);
	return 0;
}
